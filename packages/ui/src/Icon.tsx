export type IconName = keyof typeof icons;
export function Icon({ name, size = 16 }: { name: IconName; size?: number }) {
  const Component = icons[name];
  return (
    <Component
      size={size}
      strokeWidth={1.75}
      aria-hidden="true"
      focusable="false"
      {...stylex.props(styles.icon)}
    />
  );
}
